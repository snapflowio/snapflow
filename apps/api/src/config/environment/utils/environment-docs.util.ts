import { z } from 'zod';
import { DeploymentEnvironment } from '../../enums/deployment-environment.enum';
import { ENVIRONMENT_NAMESPACES } from '../registry.environment';
import { ENVIRONMENT_METADATA } from './environment-variable.util';

interface DocumentedVariable {
	name: string;
	type: string;
	description: string;
	defaultValue: string | undefined;
	required: boolean;
	secret: boolean;
	requiredIn: readonly string[];
	allowedIn: readonly string[];
}

type JsonSchemaProperty = Readonly<{
	type?: string;
	enum?: readonly unknown[];
	default?: unknown;
	description?: string;
	secret?: boolean;
	requiredIn?: readonly string[];
	allowedIn?: readonly string[];
}>;

const GENERATED_NOTICE =
	'Generated by `moon run api:env-docs` from apps/api/src/config/environment; do not edit.';
const SELECTOR = 'SNAPFLOW_ENVIRONMENT';
const SECRET_PLACEHOLDER = '(secret)';

function documentedVariables(
	namespace: (typeof ENVIRONMENT_NAMESPACES)[number]
): DocumentedVariable[] {
	const schema = z.toJSONSchema(namespace.schema, {
		io: 'input',
		unrepresentable: 'any',
		metadata: ENVIRONMENT_METADATA,
	});
	const properties = (schema.properties ?? {}) as Readonly<
		Record<string, JsonSchemaProperty>
	>;
	const required = new Set(schema.required ?? []);
	return Object.entries(properties).map(([name, property]) => ({
		name,
		type: property.enum
			? property.enum.join(' \\| ')
			: (property.type ?? 'string'),
		description: property.description ?? '',
		defaultValue:
			property.default === undefined ? undefined : String(property.default),
		required: required.has(name),
		secret: property.secret === true,
		requiredIn: property.requiredIn ?? [],
		allowedIn: property.allowedIn ?? [],
	}));
}

function shown(
	variable: DocumentedVariable,
	value: string | undefined
): string {
	if (value === undefined) return '';
	return variable.secret ? SECRET_PLACEHOLDER : value;
}

export function environmentFileSections(): {
	title: string;
	names: string[];
}[] {
	return ENVIRONMENT_NAMESPACES.map((namespace) => {
		const shape: Readonly<Record<string, z.ZodType>> = namespace.schema.shape;
		return {
			title: namespace.title,
			names: Object.keys(shape).filter((name) => {
				const allowedIn = ENVIRONMENT_METADATA.get(shape[name])?.allowedIn;
				return (
					!allowedIn || allowedIn.includes(DeploymentEnvironment.DEVELOPMENT)
				);
			}),
		};
	});
}

function tableCell(value: string): string {
	return value.replaceAll('|', '\\|').replaceAll('\n', ' ');
}

export function renderEnvironmentReference(): string {
	const sections = ENVIRONMENT_NAMESPACES.map((namespace) => {
		const rows = documentedVariables(namespace).map((variable) =>
			[
				`\`${variable.name}\``,
				variable.type,
				shown(variable, variable.defaultValue),
				[
					variable.required ? 'all' : variable.requiredIn.join(', '),
					variable.allowedIn.length > 0
						? `only ${variable.allowedIn.join(', ')}`
						: '',
				]
					.filter(Boolean)
					.join('; '),
				variable.secret ? 'yes' : '',
				tableCell(variable.description),
			].join(' | ')
		);
		return [
			`## ${namespace.title}`,
			'',
			namespace.description,
			...(namespace.note ? ['', namespace.note] : []),
			'',
			'| Variable | Type | Default | Required | Secret | Description |',
			'| --- | --- | --- | --- | --- | --- |',
			...rows.map((row) => `| ${row} |`),
		].join('\n');
	});
	return [
		'# API environment',
		'',
		`<!-- ${GENERATED_NOTICE} -->`,
		'',
		`\`${SELECTOR}\` selects the deployment profile: whether the deployment is hosted (HTTPS origins, loopback Vault Proxy, verified database TLS, no localhost domain, no test keys) and whether logs and audit entries go to a developer console. Every application value comes from the environment, and code holds no deployment values: a local apps/api/.env (gitignored; it lists every variable development may set, in the sections below, and an empty value counts as unset) sets them in development; in production Kubernetes sets them from OpenBao through the External Secrets Operator. Secrets have no default. Runtime settings live in the settings system, and policy in versioned \`*_POLICY\` constants.`,
		'',
		...sections.flatMap((section) => [section, '']),
	].join('\n');
}
